#!/usr/bin/env node
/**
 * Writes src/lib/packs/bundled.ts — the map of the bundled content snapshot (assets/packs/<section>/*.pack)
 * as Metro asset requires, plus each section's version read from its index.pack.
 *
 *   npm run packs:bundle
 *   node scripts/gen-bundled.mjs [--packs <dir>] [--out <file>] [--check]
 *
 * - A section whose folder is missing or has no index.pack is `null` (the app then has no bundled copy).
 * - Fails (exit 1) when index.pack is invalid or refers to a chunk file that is not there.
 * - Output is deterministic (sorted, no timestamps) and only rewritten when it changes.
 * - --check: exit 1 if the file on disk is not up to date (for CI), without writing.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SECTIONS = ["names", "sunan"];

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : fallback;
}

const PACKS = arg("--packs", join(ROOT, "assets", "packs"));
const OUT = arg("--out", join(ROOT, "src", "lib", "packs", "bundled.ts"));
const CHECK = process.argv.includes("--check");

const byName = (a, b) => (a === b ? 0 : a === "index.pack" ? -1 : b === "index.pack" ? 1 : a < b ? -1 : 1);

function fail(msg) {
  console.error(`packs:bundle — ${msg}`);
  process.exit(1);
}

function scanSection(section) {
  const dir = join(PACKS, section);
  if (!existsSync(dir)) return null;
  const packs = readdirSync(dir)
    .filter((f) => f.endsWith(".pack"))
    .sort(byName);
  if (!packs.includes("index.pack")) {
    if (packs.length) fail(`${section}: ${packs.length} .pack files but no index.pack`);
    return null;
  }
  let index;
  try {
    index = JSON.parse(readFileSync(join(dir, "index.pack"), "utf8").replace(/^\uFEFF/, ""));
  } catch (e) {
    fail(`${section}/index.pack is not valid JSON (${e.message})`);
  }
  if (index?.kind !== section) fail(`${section}/index.pack: kind is ${JSON.stringify(index?.kind)}, expected "${section}"`);
  if (typeof index.version !== "string" || !index.version) fail(`${section}/index.pack has no version`);
  const present = new Set(packs.map((f) => f.replace(/\.pack$/, ".json")));
  const missing = (Array.isArray(index.chunks) ? index.chunks : [])
    .map((c) => c?.file)
    .filter((f) => typeof f === "string" && !present.has(f));
  if (missing.length) fail(`${section}: index.pack lists files that are missing: ${missing.join(", ")}`);
  return { version: index.version, packs, dir };
}

function requirePath(file) {
  let p = relative(dirname(OUT), file).split(sep).join("/");
  if (!p.startsWith(".")) p = `./${p}`;
  return p;
}

const lines = [
  "/* eslint-disable */",
  "// AUTO-GENERATED by scripts/gen-bundled.mjs (`npm run packs:bundle`). Do not edit by hand.",
  "// The bundled content snapshot: assets/packs/<section>/*.pack, required as Metro assets.",
  'import type { BundledPacks } from "./bundled-types";',
  "",
  "export const BUNDLED: BundledPacks = {",
];
const summary = [];
for (const section of SECTIONS) {
  const s = scanSection(section);
  if (!s) {
    lines.push(`  ${section}: null,`);
    summary.push(`${section}: none`);
    continue;
  }
  lines.push(`  ${section}: {`);
  lines.push(`    version: ${JSON.stringify(s.version)},`);
  lines.push("    files: {");
  for (const f of s.packs) {
    const json = f.replace(/\.pack$/, ".json");
    lines.push(`      ${JSON.stringify(json)}: require(${JSON.stringify(requirePath(join(s.dir, f)))}),`);
  }
  lines.push("    },");
  lines.push("  },");
  summary.push(`${section}: ${s.version} (${s.packs.length} files)`);
}
lines.push("};", "");
const text = lines.join("\n");

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
if (CHECK) {
  if (current !== text) fail(`${relative(ROOT, OUT)} is out of date — run npm run packs:bundle`);
  console.log(`packs:bundle — up to date (${summary.join("; ")})`);
} else if (current === text) {
  console.log(`packs:bundle — unchanged (${summary.join("; ")})`);
} else {
  writeFileSync(OUT, text, "utf8");
  console.log(`packs:bundle — wrote ${relative(ROOT, OUT)} (${summary.join("; ")})`);
}
